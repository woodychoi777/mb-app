# traits_desc를 results_map에 추가
for mbti, descs in traits_desc.items():
    # 해당 유형의 traits 필드 뒤에 traits_desc 추가
    search = f'"traits": "{"+".join(descs.keys())}'
    # traits 값 찾기
    import re
    pattern = f'("{mbti}".*?"traits": ".*?")'
    match = re.search(pattern, content, re.DOTALL)
    if match:
        old = match.group(1)
        # traits_desc 딕셔너리를 문자열로 변환
        desc_items = []
        for k, v in descs.items():
            v_escaped = v.replace('"', '\\"')
            desc_items.append(f'            "{k}": "{v_escaped}"')
        desc_str = "{\n" + ",\n".join(desc_items) + "\n        }"
        new = old + f',\n        "traits_desc": {desc_str}'
        content = content.replace(old, new)
        print(f"✓ {mbti} traits_desc 추가")
    else:
        print(f"✗ {mbti} 실패")

with open('app.py', 'w', encoding='utf-8') as f:
    f.write(content)

